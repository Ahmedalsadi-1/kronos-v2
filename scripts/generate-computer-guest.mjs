import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";

const directory = new URL("../emain/linux-desktop/guest/", import.meta.url);
const source = Object.fromEntries(
  await Promise.all(
    ["appearance.sh", "focus-one.sh", "open-app.sh", "pick-element.py", "session.sh"].map(async (name) => [
      name,
      await readFile(new URL(name, directory), "utf8"),
    ])
  )
);
const output = new URL("../emain/linux-desktop/guest-assets.ts", import.meta.url);
await writeFile(
  output,
  `// Generated by scripts/generate-computer-guest.mjs. Edit guest/ sources and regenerate.\nexport const LinuxGuestSources = ${JSON.stringify(source, null, 4)};\n`
);
process.stdout.write(`${fileURLToPath(output)}\n`);
